"""Build, check and prepare the review of the Juris-Eval seed set (PLAN 5.1).

The source is ``eval/juris_eval/items.yaml``. Commands:

    uv run scripts/juris_eval.py build [--check]
        write dev.jsonl, test.jsonl and schema.json from items.yaml
        (--check: exit 1 if the committed files are stale, write nothing)
    uv run scripts/juris_eval.py check
        validate every item against the corpus database: each gold authority is a judgment
        in the corpus, its citation is the document's own, its pinpoints are paragraphs of
        the judgment, and each gold section exists
    uv run scripts/juris_eval.py review [--out eval/juris_eval/REVIEW.md]
        write a review sheet: every item with the corpus text of each pinpoint, for a human
        reviewer to check the propositions against the judgments
"""

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

from sqlalchemy import create_engine, text
from sqlalchemy.engine import Connection

from juris.config import get_settings
from juris.eval.juris_eval import (
    EVAL_DIR,
    SPLITS,
    JurisEvalItem,
    check_against_corpus,
    load_source,
    schema,
    split_lines,
)

EXCERPT = 900  # characters of each pinpoint paragraph in the review sheet


def outputs(items: list[JurisEvalItem]) -> dict[Path, str]:
    files = {EVAL_DIR / f"{s}.jsonl": split_lines(items, s) for s in SPLITS}
    files[EVAL_DIR / "schema.json"] = json.dumps(schema(), indent=2, ensure_ascii=False) + "\n"
    return files


def build(check: bool) -> int:
    items = load_source()
    stale = []
    for path, content in outputs(items).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path.name)
            if not check:
                path.write_bytes(content.encode("utf-8"))  # LF endings on every OS
    counts = Counter(i.split for i in items)
    print(f"{len(items)} items: dev {counts['dev']}, test {counts['test']}")
    if check and stale:
        print(f"stale: {', '.join(stale)} (run: uv run scripts/juris_eval.py build)")
        return 1
    print("up to date" if check or not stale else f"wrote {', '.join(stale)}")
    return 0


def check_corpus() -> int:
    items = load_source()
    engine = create_engine(get_settings().database_url())
    with engine.connect() as conn:
        problems = check_against_corpus(conn, items)
    authorities = {
        a.doc_id
        for i in items
        for a in (*i.gold_supporting_authorities, *i.gold_contrary_authorities)
    }
    pinpoints = sum(
        len(a.pinpoints)
        for i in items
        for a in (*i.gold_supporting_authorities, *i.gold_contrary_authorities)
    )
    print(
        f"{len(items)} items, {len(authorities)} distinct authorities, {pinpoints} pinpoints, "
        f"{len({s for i in items for s in i.gold_sections})} sections"
    )
    for p in problems:
        print(f"  PROBLEM {p}")
    print("all resolve to the corpus" if not problems else f"{len(problems)} problems")
    return 1 if problems else 0


def _words(s: str) -> set[str]:
    return {w for w in re.findall(r"[a-z]{5,}", s.lower())}


def _paragraph(conn: Connection, doc_id: str, no: str, proposition: str) -> str:
    """The paragraph, or for a long one the window sharing the most words with the
    proposition (headnotes often cover several points)."""
    body = conn.execute(
        text("SELECT text FROM paragraphs WHERE doc_id = :d AND no = :n ORDER BY seq LIMIT 1"),
        {"d": doc_id, "n": no},
    ).scalar()
    flat = " ".join((body or "").split())
    if len(flat) <= EXCERPT:
        return flat
    wanted = _words(proposition)
    starts = range(0, len(flat) - EXCERPT + 1, 100)
    best = max(starts, key=lambda s: (len(_words(flat[s : s + EXCERPT]) & wanted), -s))
    head = "… " if best else ""
    tail = " …" if best + EXCERPT < len(flat) else ""
    return head + flat[best : best + EXCERPT] + tail


def review(out: Path) -> int:
    items = load_source()
    engine = create_engine(get_settings().database_url())
    lines = [
        "# Juris-Eval seed set: review sheet",
        "",
        "Generated by `scripts/juris_eval.py review` from `items.yaml` and the corpus database. "
        "For each item, check that the question and key points are sound, and that every "
        "authority's proposition is supported by the quoted pinpoint paragraphs (OCR errors "
        "are the corpus's own). Record a review by setting `reviewed_by` in `items.yaml`.",
        "",
        "Judgment text: Supreme Court judgments from the AWS Open Data registry, CC-BY-4.0 "
        "(`docs/DATA_NOTICE.md`). Paragraph labels: `h-` headnote, `f-` front matter, `p-` "
        "unnumbered body paragraph, plain numbers are the Court's paragraph numbers.",
        "",
    ]
    with engine.connect() as conn:
        for item in sorted(items, key=lambda i: i.id):
            lines += [
                f"## {item.id} ({item.split}, {item.difficulty}): {item.topic}",
                "",
                f"**Question.** {item.question}",
                "",
                f"**Facts.** {item.facts}",
                "",
                "**Issues.**",
                *[f"- {x}" for x in item.gold_issues],
                "",
                f"**Sections.** {', '.join(item.gold_sections)}",
                "",
                "**Key points.**",
                *[f"- {x}" for x in item.key_points],
                "",
            ]
            for kind, authorities in (
                ("Supporting", item.gold_supporting_authorities),
                ("Contrary", item.gold_contrary_authorities),
            ):
                for a in authorities:
                    lines += [
                        f"**{kind}: {a.title}**, {a.citation} (`{a.doc_id}`)",
                        "",
                        f"Proposition: {a.proposition}",
                        "",
                    ]
                    for no in a.pinpoints:
                        excerpt = _paragraph(conn, a.doc_id, no, a.proposition)
                        lines += [f"> ¶ {no}: {excerpt}", ""]
            if item.notes:
                lines += [f"**Notes.** {item.notes}", ""]
            lines += [f"**Reviewed by:** {item.reviewed_by or '—'}", "", "---", ""]
    out.write_bytes(("\n".join(lines).rstrip() + "\n").encode("utf-8"))
    print(f"wrote {out} ({len(items)} items)")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="command", required=True)
    b = sub.add_parser("build")
    b.add_argument("--check", action="store_true")
    sub.add_parser("check")
    r = sub.add_parser("review")
    r.add_argument("--out", type=Path, default=EVAL_DIR / "REVIEW.md")
    args = ap.parse_args(argv)
    if args.command == "build":
        return build(args.check)
    if args.command == "check":
        return check_corpus()
    return review(args.out)


if __name__ == "__main__":
    sys.exit(main())
